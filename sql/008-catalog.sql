SET NAMES utf8mb4;

CREATE TABLE IF NOT EXISTS catalog_items (
  id INT PRIMARY KEY,
  shop_type VARCHAR(60) NOT NULL,
  sub_cat   VARCHAR(60) DEFAULT NULL,
  name_en   VARCHAR(90) NOT NULL,
  name_hi   VARCHAR(90) DEFAULT NULL,
  unit_hint VARCHAR(20) NOT NULL DEFAULT 'पीस',
  is_sewa   TINYINT(1) NOT NULL DEFAULT 0,
  sort_no   INT NOT NULL DEFAULT 0,
  INDEX idx_ci_type (shop_type),
  INDEX idx_ci_name (name_en),
  INDEX idx_ci_hi (name_hi)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

